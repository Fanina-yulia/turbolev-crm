CREATE OR REPLACE FUNCTION turbolev_sync_warranty_task()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  task_key TEXT := 'warranty:' || NEW."id" || ':action';
  work_order_id TEXT;
  assignee TEXT;
  title TEXT;
  priority TEXT;
  due_at TIMESTAMP(3);
BEGIN
  SELECT wol."workOrderId" INTO work_order_id
    FROM "WorkOrderLine" wol
   WHERE wol."id" = NEW."workOrderLineId"
   LIMIT 1;

  assignee := COALESCE(NEW."openedByUserId", turbolev_task_assignee_for_work_order(work_order_id));

  IF NEW."status"::text = 'OPEN' THEN
    title := 'Опрацювати нове гарантійне звернення';
    priority := 'HIGH';
    due_at := CURRENT_TIMESTAMP + INTERVAL '2 hours';
  ELSIF NEW."status"::text = 'REVIEW' THEN
    title := 'Прийняти рішення по гарантійному зверненню';
    priority := 'HIGH';
    due_at := CURRENT_TIMESTAMP + INTERVAL '4 hours';
  ELSIF NEW."status"::text = 'APPROVED' THEN
    title := 'Організувати виконання гарантійних робіт';
    priority := 'HIGH';
    due_at := CURRENT_TIMESTAMP + INTERVAL '1 day';
  ELSE
    PERFORM turbolev_close_process_task(task_key);
    RETURN NEW;
  END IF;

  PERFORM turbolev_upsert_process_task(
    task_key, title, priority, assignee, due_at,
    'WARRANTY', NEW."id", work_order_id, NULL, 'Гарантії', NEW."status"::text
  );
  RETURN NEW;
END;
$$;

