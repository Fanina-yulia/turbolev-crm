CREATE OR REPLACE FUNCTION turbolev_sync_payment_task()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  task_key TEXT := 'payment:' || NEW."id" || ':receivable';
  assignee TEXT;
  fallback_user TEXT;
  title TEXT;
  priority TEXT;
  due_at TIMESTAMP(3);
BEGIN
  IF NEW."direction"::text <> 'RECEIVABLE' OR NEW."workOrderId" IS NULL THEN
    PERFORM turbolev_close_process_task(task_key);
    RETURN NEW;
  END IF;

  assignee := turbolev_task_assignee_for_work_order(NEW."workOrderId");
  IF assignee IS NULL AND NEW."sourceEventId" IS NOT NULL THEN
    SELECT fe."createdById" INTO fallback_user
      FROM "FinancialEvent" fe
     WHERE fe."id" = NEW."sourceEventId"
     LIMIT 1;
    assignee := fallback_user;
  END IF;

  IF NEW."status"::text = 'OPEN' THEN
    title := 'Отримати оплату від клієнта';
    priority := 'HIGH';
    due_at := COALESCE(NEW."dueAt", CURRENT_TIMESTAMP + INTERVAL '1 day');
  ELSIF NEW."status"::text = 'PARTIALLY_PAID' THEN
    title := 'Отримати залишок оплати від клієнта';
    priority := 'HIGH';
    due_at := COALESCE(NEW."dueAt", CURRENT_TIMESTAMP + INTERVAL '1 day');
  ELSIF NEW."status"::text = 'OVERDUE' THEN
    title := 'Прострочена оплата: зв’язатися з клієнтом';
    priority := 'CRITICAL';
    due_at := CURRENT_TIMESTAMP;
  ELSE
    PERFORM turbolev_close_process_task(task_key);
    RETURN NEW;
  END IF;

  PERFORM turbolev_upsert_process_task(
    task_key, title, priority, assignee, due_at,
    'PAYMENT', NEW."id", NEW."workOrderId", 'payment', 'Замовлення-наряди', NEW."status"::text
  );
  RETURN NEW;
END;
$$;

