CREATE TRIGGER "PartsRequest_task_after_insert"
AFTER INSERT ON "PartsRequest"
FOR EACH ROW EXECUTE FUNCTION turbolev_sync_parts_request_task();

DROP TRIGGER IF EXISTS "PartsRequest_task_after_update" ON "PartsRequest";
CREATE TRIGGER "PartsRequest_task_after_update"
