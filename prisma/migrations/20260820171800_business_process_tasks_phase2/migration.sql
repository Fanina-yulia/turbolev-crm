CREATE OR REPLACE FUNCTION turbolev_work_order_location_id(p_work_order_id TEXT)
RETURNS TEXT
LANGUAGE SQL
STABLE
AS $$
  SELECT sa."locationId"
  FROM "ServiceAppointment" sa
  WHERE sa."workOrderId" = p_work_order_id
  ORDER BY sa."updatedAt" DESC, sa."createdAt" DESC
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION turbolev_work_order_responsible_user(p_work_order_id TEXT, p_role_codes TEXT[])
RETURNS TEXT
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
  location_id TEXT;
  target_user_id TEXT;
BEGIN
  location_id := turbolev_work_order_location_id(p_work_order_id);

  SELECT uar."userId"
    INTO target_user_id
  FROM "UserAccessRole" uar
  JOIN "AccessRole" ar ON ar."id" = uar."roleId"
  JOIN "User" u ON u."id" = uar."userId"
  WHERE uar."isActive" = TRUE
    AND ar."isActive" = TRUE
    AND u."isActive" = TRUE
    AND uar."startsAt" <= CURRENT_TIMESTAMP
    AND (uar."endsAt" IS NULL OR uar."endsAt" > CURRENT_TIMESTAMP)
    AND ar."code" = ANY(p_role_codes)
    AND (location_id IS NULL OR uar."locationId" = location_id OR uar."locationId" IS NULL)
  ORDER BY
    CASE WHEN location_id IS NOT NULL AND uar."locationId" = location_id THEN 0 ELSE 1 END,
    array_position(p_role_codes, ar."code"),
    uar."isPrimary" DESC,
    uar."createdAt" ASC
  LIMIT 1;

  IF target_user_id IS NOT NULL THEN
    RETURN target_user_id;
  END IF;

  SELECT sa."createdById"
    INTO target_user_id
  FROM "ServiceAppointment" sa
  JOIN "User" u ON u."id" = sa."createdById" AND u."isActive" = TRUE
  WHERE sa."workOrderId" = p_work_order_id
    AND sa."createdById" IS NOT NULL
  ORDER BY sa."updatedAt" DESC, sa."createdAt" DESC
  LIMIT 1;

  IF target_user_id IS NOT NULL THEN
    RETURN target_user_id;
  END IF;

  SELECT l."assignedUserId"
    INTO target_user_id
  FROM "WorkOrder" wo
  JOIN "DiagnosticRequest" dr ON dr."id" = wo."diagnosticRequestId"
  JOIN "Lead" l ON l."id" = dr."leadId"
  JOIN "User" u ON u."id" = l."assignedUserId" AND u."isActive" = TRUE
  WHERE wo."id" = p_work_order_id
    AND l."assignedUserId" IS NOT NULL
  LIMIT 1;

  RETURN target_user_id;
END;
$$;

CREATE OR REPLACE FUNCTION turbolev_work_order_context(p_work_order_id TEXT)
RETURNS TABLE(client_id TEXT, vehicle_id TEXT)
LANGUAGE SQL
STABLE
AS $$
  SELECT wo."clientId", wo."vehicleId"
  FROM "WorkOrder" wo
  WHERE wo."id" = p_work_order_id;
$$;

CREATE OR REPLACE FUNCTION turbolev_sync_estimate_task()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  task_key TEXT := 'estimate:' || NEW."id" || ':decision';
  target_user_id TEXT;
  ctx RECORD;
BEGIN
  IF NEW."status"::text = 'SENT' THEN
    target_user_id := turbolev_work_order_responsible_user(
      NEW."workOrderId",
      ARRAY['SERVICE_ADVISOR','STATION_MANAGER','OWNER','EXECUTIVE_DIRECTOR']
    );
    SELECT * INTO ctx FROM turbolev_work_order_context(NEW."workOrderId");

    IF target_user_id IS NOT NULL THEN
      INSERT INTO "CrmTask" (
        "id", "title", "description", "status", "priority", "assignedUserId", "dueAt",
        "sourceType", "sourceId", "clientId", "vehicleId", "autoGenerated", "dedupeKey", "metadata", "createdAt", "updatedAt"
