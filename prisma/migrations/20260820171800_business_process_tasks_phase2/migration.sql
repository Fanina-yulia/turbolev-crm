  task_key TEXT := 'payment:' || NEW."id" || ':receivable';
  target_user_id TEXT;
  ctx RECORD;
  task_title TEXT;
  task_priority TEXT;
  task_due TIMESTAMP(3);
  outstanding NUMERIC;
BEGIN
  IF NEW."direction"::text = 'RECEIVABLE'
     AND NEW."workOrderId" IS NOT NULL
     AND NEW."status"::text IN ('OPEN','PARTIALLY_PAID','OVERDUE') THEN
    target_user_id := turbolev_work_order_responsible_user(
      NEW."workOrderId",
      ARRAY['ACCOUNTANT','STATION_MANAGER','OWNER','EXECUTIVE_DIRECTOR']
