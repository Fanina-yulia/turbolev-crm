type Task = {
  id: string;
  title: string;
  description: string | null;
  status: string;
  priority: string;
  dueAt: string | null;
  autoGenerated: boolean;
};

type AttentionCategory =
  | "COMMUNICATIONS"
  | "SERVICE"
  | "DIAGNOSTICS"
  | "PARTS"
  | "SUPPLIERS"
  | "FINANCE"
  | "PAYROLL"
  | "POSTS"
  | "QUALITY"
  | "WARRANTY"
  | "MANUAL";

type AttentionLevel = "CRITICAL" | "HIGH" | "MEDIUM" | "LOW";
type AttentionBucket = "ACTION" | "WAITING" | "MONITORING";
type AttentionAction = { label: string; section: string; params?: Record<string, string> };

type AttentionSignal = {
  id: string;
  sourceType: string;
  sourceId: string | null;
  taskId: string | null;
  title: string;
  description: string | null;
  reason: string;
  category: AttentionCategory;
  level: AttentionLevel;
  bucket: AttentionBucket;
  dueAt: string | null;
  occurredAt: string;
  isOverdue: boolean;
  overdueMinutes: number;
  isToday: boolean;
  autoGenerated: boolean;
  amount: number | null;
  currency: string | null;
  counterparty: string | null;
  action: AttentionAction | null;
  metadata: Record<string, unknown>;
};

type PostLoadPeriod = {
  date: string;
  utilizationPct: number;
  bookedHours: number;
  capacityHours: number;
  activePosts: number;
  posts: Array<{
    id: string;
    name: string;
    locationName: string;
    utilizationPct: number;
    bookedHours: number;
    capacityHours: number;
  }>;
};

type AttentionCenter = {
  signals: AttentionSignal[];
  summary: { total: number; critical: number; overdue: number; action: number; waiting: number; today: number };
  categories: Record<AttentionCategory, number>;
  postLoad: { today: PostLoadPeriod | null; tomorrow: PostLoadPeriod | null };
  generatedAt: string;
};

type Payload = { ok?: boolean; tasks?: Task[]; attention?: AttentionCenter; error?: string };
type ViewFilter = "ALL" | "CRITICAL" | "OVERDUE" | "ACTION" | "WAITING" | "TODAY" | "ARCHIVE";
type CategoryFilter = "ALL" | AttentionCategory;

